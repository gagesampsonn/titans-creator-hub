import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createImageLedger } from './image-ledger.mjs';
import pg from 'pg';
import { readFile } from 'node:fs/promises';

// This integration suite is intentionally explicit, never silently skipped.
// The launcher provisions an isolated PostgreSQL test database, not live accounts.
test('image ledger: lifetime allowance, races, failures, refunds and spend caps', async () => {
  assert.ok(process.env.TITANS_IMAGE_TEST_DATABASE_URL, 'A dedicated test database is required');
  const setup = new pg.Pool({ connectionString: process.env.TITANS_IMAGE_TEST_DATABASE_URL });
  assert.match((await setup.query('SELECT current_database() AS name')).rows[0].name, /^titans_images_test_[a-f0-9]{16}$/);
  await setup.query(await readFile(new URL('./image-schema.sql', import.meta.url), 'utf8'));
  await setup.query('UPDATE titans_images.settings SET generation_enabled=true');
  const ledger = createImageLedger({ connectionString: process.env.TITANS_IMAGE_TEST_DATABASE_URL });
  try {
    const user = `user_${randomUUID().replaceAll('-', '')}`;
    await assert.rejects(ledger.ensureAllowance(user, false), /access_required/);
    await Promise.all(Array.from({ length: 15 }, () => ledger.ensureAllowance(user, true)));
    assert.equal((await ledger.account(user)).balance, 15);
    const id = randomUUID();
    const request = { id, userId: user, hash: 'a'.repeat(64), kind: 'original' };
    const duplicates = await Promise.all(Array.from({ length: 8 }, () => ledger.reserve(request)));
    assert.equal(duplicates.filter(x => x.created).length, 1);
    assert.equal((await ledger.account(user)).available, 14);
    await assert.rejects(ledger.reserve({ ...request, hash: 'b'.repeat(64) }), /request_conflict/);
    await assert.rejects(ledger.reserve({ ...request, id: randomUUID() }), /request_in_progress/);
    await ledger.finish(id, 'unknown');
    assert.equal((await ledger.account(user)).available, 14);
    await ledger.finish(id, 'succeeded', { costMicros: 178108, usage: { textTokens: 236, imageTokens: 1536, outputTokens: 5488 } });
    await ledger.finish(id, 'succeeded', { costMicros: 178108 });
    assert.equal((await ledger.account(user)).balance, 14);
    await ledger.ensureAllowance(user, true);
    assert.equal((await ledger.account(user)).balance, 14);
    const failed = randomUUID();
    await ledger.reserve({ ...request, id: failed });
    await ledger.finish(failed, 'failed');
    assert.equal((await ledger.account(user)).available, 14);
    const claimed = randomUUID();
    await ledger.reserve({ ...request, id: claimed });
    await ledger.finish(claimed, 'running');
    await ledger.finish(claimed, 'failed', { expectedState: 'reserved' });
    assert.equal((await ledger.job(user, claimed)).state, 'running');
    assert.equal((await ledger.account(user)).available, 13);
    await ledger.finish(claimed, 'failed');
    assert.equal(await ledger.job('user_somebodyelse', id), null);
    const payment = { id: `pay_${randomUUID()}`, userId: user, credits: 10, priceCents: 500, refundedCents: 0 };
    await Promise.all([ledger.applyPayment(payment), ledger.applyPayment(payment)]);
    assert.equal((await ledger.account(user)).balance, 24);
    await ledger.applyPayment({ ...payment, refundedCents: 250 });
    await ledger.applyPayment({ ...payment, refundedCents: 250 });
    assert.equal((await ledger.account(user)).balance, 19);
    await ledger.applyPayment({ ...payment, refundedCents: 500 });
    await ledger.applyPayment(payment); // Delayed success cannot restore reversed credits.
    assert.equal((await ledger.account(user)).balance, 14);
    await assert.rejects(ledger.applyPayment({ ...payment, userId: 'user_other' }), /payment_conflict/);
    await setup.query('UPDATE titans_images.settings SET sales_enabled=true');
    const orderId = randomUUID();
    const orders = await Promise.all([ledger.createOrder(user, orderId, 'photos_100'), ledger.createOrder(user, orderId, 'photos_100')]);
    assert.equal(orders.filter(order => order.created).length, 1);
    assert.equal(orders[0].credits, 100); assert.equal(orders[0].price_cents, 3000);
    await assert.rejects(ledger.createOrder(user, orderId, 'photos_10'), /order_conflict/);
    await ledger.completeOrder(orderId, 'ch_test', 'plan_test', 'https://sandbox.whop.com/checkout/test');
    assert.equal((await ledger.order(orderId)).checkout_id, 'ch_test');
    await setup.query('UPDATE titans_images.settings SET sales_enabled=false');
    await assert.rejects(ledger.createOrder(user, randomUUID(), 'photos_10'), /credit_sales_paused/);
    const adjustment = { id: randomUUID(), userId: user, delta: 2, reason: 'Support adjustment test' };
    await ledger.adjust(adjustment); await ledger.adjust(adjustment);
    assert.equal((await ledger.account(user)).balance, 16);
    await assert.rejects(ledger.adjust({ ...adjustment, delta: 3 }), /adjustment_conflict/);
    await ledger.configure({ generationEnabled: false });
    await assert.rejects(ledger.reserve({ ...request, id: randomUUID() }), /generation_paused/);
    await ledger.configure({ generationEnabled: true });
    const exhausted = `user_${randomUUID().replaceAll('-', '')}`;
    await ledger.ensureAllowance(exhausted, true);
    await ledger.adjust({ id: randomUUID(), userId: exhausted, delta: -15, reason: 'Exhausted account test' });
    await assert.rejects(ledger.reserve({ ...request, userId: exhausted, id: randomUUID() }), /credits_exhausted/);
    await ledger.configurePack({ id: 'photos_10', priceCents: 600, credits: 12, enabled: true });
    assert.equal((await ledger.packs()).find(pack => pack.id === 'photos_10').credits, 12);
    assert.equal((await ledger.order(orderId)).price_cents, 3000);
    await setup.query('UPDATE titans_images.settings SET day_micros=1');
    await assert.rejects(ledger.reserve({ ...request, id: randomUUID() }), /spend_limit/);
    await ledger.configure({ dayMicros: 10000000 });
    const recoveryUser = 'user_recoverytest';
    await ledger.ensureAllowance(recoveryUser, true);
    const uncertainId = randomUUID();
    await ledger.reserve({ ...request, userId: recoveryUser, id: uncertainId });
    await ledger.finish(uncertainId, 'unknown');
    const resolution = { id: uncertainId, evidence: 'Provider confirmed no completed image for this request.', confirmedNoImage: true, costMicros: 250000 };
    await assert.rejects(ledger.resolveFailure(resolution), /recovery_too_early/);
    await setup.query("UPDATE titans_images.jobs SET updated_at=now()-interval '11 minutes' WHERE id=$1", [uncertainId]);
    await assert.rejects(ledger.resolveFailure({ ...resolution, confirmedNoImage: false }), /confirmation_required/);
    await ledger.resolveFailure(resolution);
    assert.equal((await ledger.account(recoveryUser)).available, 15);
    assert.equal((await ledger.job(recoveryUser, uncertainId)).state, 'failed');
    const oldActive = randomUUID();
    await ledger.reserve({ ...request, id: oldActive, userId: recoveryUser });
    await ledger.finish(oldActive, 'running');
    await setup.query("UPDATE titans_images.jobs SET created_at=now()-interval '31 days'");
    await ledger.configure({ dayMicros: 250000 });
    await assert.rejects(ledger.reserve({ ...request, id: randomUUID(), userId: user }), /spend_limit/);
  } finally { await ledger.close(); await setup.end(); }
});
